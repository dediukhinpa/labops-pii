"""Эвристика ФИО guard на матрице записи (25.11.2026), вымышленные данные.

Матрица из 5633 кейсов показала 674 промаха guard: имена вне словаря (Рашид, Лейла, Карл),
фамилии без привычного суффикса (Белых, Дамберг, Цой, Ким, Головач), выравнивание тремя
пробелами, отчество «-ичом». Затем и остаток (99): одиночная фамилия после глагола связи или
должности, ФИО в имени файла и пути, «Иванов.С.П.», строчное «мария ильинична», латиница.
Морфологии в guard по-прежнему нет: только окончания и словари.
"""

from __future__ import annotations

import pytest

from labops_pii.guard.names import has_person_name
from labops_pii.pii_patterns import normalize_text


def _found(text: str) -> bool:
    return has_person_name(normalize_text(text))


@pytest.mark.parametrize(
    "text",
    [
        "Алиев Рашид",
        "Рашид Алиев",
        "Гусейнова Лейла Магомед кызы",
        "Дамберг Карл Густавович",
        "Белых Ирина",
        "Белых И.",
        "В. Цой",
        "Цой Виктор",
        "Ким Елена",
        "Головач Дмитрий",
        "Петросян Анна",
        "Чавчавадзе Нина",
        "Шевчук Наталья",
        "Иванов  Сергей   Петрович",
        "Согласовать с Головачом Дмитрием Ильичом.",
        "Саша Петров и Маша Иванова придут",
        "алиев рашид мамедович",
        # одиночная фамилия после слова-признака
        "Звонил Дамберг, просил перезвонить.",
        "Звонил Белых, просил перезвонить.",
        "Звонил Новикова-Прибой, просил перезвонить.",
        "позвони Петрову, пожалуйста",
        "Менеджер: Петрова",
        "Звонил Вишневский, просил",
        # имя файла, путь, точки без пробелов
        "Файл Договор_Иванов_С.П.docx отправлен",
        "/home/docs/Петрова_Анна/паспорт.pdf",
        "Исполнитель: Иванов.С.П.",
        # строчное отчество на «-ична» от «-ич»
        "новикова-прибой мария ильинична",
        "анна никитична",
        # латиница
        "John Smith",
        "Smith John",
        "Contact: HANS MÜLLER",
        "Ivanov Sergey",
        "--\nBest regards,\nSergey Ivanov\nHead of Sales",
    ],
)
def test_found(text: str) -> None:
    assert _found(text), text


@pytest.mark.parametrize(
    "text",
    [
        "Врач Анна",
        "Ноутбук Андрей забрал",
        "Новых Анна не нашла",
        "Других В. вариантов нет",
        "Тягач Иван пригнал",
        "Айсберг В. растаял",
        "Склад Иван",
        # слово-признак, но за ним не фамилия
        "Звонил Сергей",
        "Склад: Петрова",
        "Поставщик Московский завод",
        "Подписал Минфин",
        "Магазин Пушкин",
        "Иван Ростов-на-Дону",
        "config_Иванов_test",
        # «-ична» без основы отчества
        "мария цинична",
        "Это практична и логична",
        # латиница без пары «имя + слово»
        "Santa Barbara",
        "Hugo Boss",
        "Visual Studio Code",
        "Yesterday Anna went home",
    ],
)
def test_not_found(text: str) -> None:
    assert not _found(text), text
