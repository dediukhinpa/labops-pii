"""Эвристика ФИО guard на матрице записи (25.11.2026), вымышленные данные.

Матрица из 5633 кейсов показала 674 промаха guard: имена вне словаря (Рашид, Лейла, Карл),
фамилии без привычного суффикса (Белых, Дамберг, Цой, Ким, Головач), выравнивание тремя
пробелами, отчество «-ичом». Морфологии в guard по-прежнему нет: только окончания и словари.
"""

from __future__ import annotations

import pytest

from labops_pii.guard.names import has_person_name
from labops_pii.pii_patterns import normalize_text


def _found(text: str) -> bool:
    return has_person_name(normalize_text(text))


@pytest.mark.parametrize(
    "text",
    [
        "Алиев Рашид",
        "Рашид Алиев",
        "Гусейнова Лейла Магомед кызы",
        "Дамберг Карл Густавович",
        "Белых Ирина",
        "Белых И.",
        "В. Цой",
        "Цой Виктор",
        "Ким Елена",
        "Головач Дмитрий",
        "Петросян Анна",
        "Чавчавадзе Нина",
        "Шевчук Наталья",
        "Иванов  Сергей   Петрович",
        "Согласовать с Головачом Дмитрием Ильичом.",
        "Саша Петров и Маша Иванова придут",
        "алиев рашид мамедович",
    ],
)
def test_found(text: str) -> None:
    assert _found(text), text


@pytest.mark.parametrize(
    "text",
    [
        "Врач Анна",
        "Ноутбук Андрей забрал",
        "Новых Анна не нашла",
        "Других В. вариантов нет",
        "Тягач Иван пригнал",
        "Айсберг В. растаял",
        "Склад Иван",
    ],
)
def test_not_found(text: str) -> None:
    assert not _found(text), text
