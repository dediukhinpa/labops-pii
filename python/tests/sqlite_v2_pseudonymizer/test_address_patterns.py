@pytest.mark.parametrize(("text", "fragment"), POSITIVE)
def test_street_house_found(text: str, fragment: str | None) -> None:
    """Улица+дом (сокращения, падежи, порядок слов) находятся ровно по границам адреса."""
    spans = find_address_spans(text)
    if fragment is None:
        assert spans == []
        return
    assert [text[a:b] for a, b in spans] == [fragment]
    assert has_street_house(text)


@pytest.mark.parametrize("text", NEGATIVE)
def test_no_false_positive(text: str) -> None:
    """Артикулы, размеры, ГОСТ, примечания, цены, счета и «ул.» в названиях не адрес."""
    assert find_address_spans(text) == []
    assert not has_street_house(text)


def test_index_with_city_between_is_separate_span() -> None:
    """Индекс, отделённый городом, маскируется отдельно: город остаётся открытым."""
    text = "119019, г. Москва, ул. Арбат, д. 1"
    assert [text[a:b] for a, b in find_address_spans(text)] == ["119019", "ул. Арбат, д. 1"]
    # guard видит только «улица + дом»: отдельный индекс без улицы адресом не считается
    assert [text[a:b] for a, b in find_street_house_spans(text)] == ["ул. Арбат, д. 1"]


def test_fullwidth_and_nbsp_normalized() -> None:
    """Неразрывные пробелы и нестандартные тире не обходят шаблон; позиции сохраняются."""
    text = "ул. Ленина, д. 5"
    assert find_address_spans(text) == [(0, len(text))]
    text = "пр‑т Мира, 10"
    assert find_address_spans(text) == [(0, len(text))]


@pytest.mark.parametrize(
    "unit",
    [
        "ул. Ленина" + " " * 40,
        "Ленина ул." + " " * 40,
        "дом 5 " + " " * 40,
        "ул. Ленина, д. 5, кв. 1, ",
        "119019, а, ",
        "г. Москва, ",
        "адрес а ",
        "Аа ",
    ],
)
def test_linear_time_on_hostile_input(unit: str) -> None:
    """Рост времени при росте входа в 8 раз - не квадратичный (нет катастрофического отката)."""
    def run(n: int) -> float:
        text = unit * n
        started = time.perf_counter()
        find_address_spans(text)
        return time.perf_counter() - started

    run(200)  # прогрев кэшей регулярных выражений
    small, large = max(run(2_000), 1e-3), run(16_000)
    # линейно было бы ~8x; квадратично ~64x. Порог 24x оставляет запас на шум.
    assert large / small < 24, (small, large)
