/**
 * Отвлечённые и неодушевлённые существительные по суффиксу («Новости», «Решение», «Станция»):
 * в Python их отсекает морфология (фамилия - одушевлённое), в TS - окончание.
 */
const ABSTRACT_NOUN_RE = new RegExp(
  '(?:ость|ости|остью|остей|ение|ения|ению|ением|ений|ание|ания|анию|анием|аний|' +
    'ство|ства|ству|ством|ция|ции|цию|цией|ций)$',
);
/**
 * Окончания, с которыми основа роли встречается в тексте («Сотруднику», «Главой»). Без «-ов»:
 * иначе «Дедов», «Другов», «Сынов» стали бы ролями.
 */
const ROLE_ENDINGS =
  '(?:а|я|у|ю|о|ом|ем|ой|ей|е|ы|и|ь|ья|ого|его|ому|ему|ым|им|ий|ый|ая|ую|ое|ые|их|ых|ам|ами|ах)?';
const NOT_SURNAME_WORD_RE = new RegExp(`^(?:${NOT_SURNAME_STEMS.join('|')})${ROLE_ENDINGS}$`);
/** Глагол по окончанию: «Позвоните», «Звонил», «Передать», «Пишет». */
const VERB_LIKE_RE =
  /(?:ть|ться|тся|тесь|ите|ете|йте|ьте|ал|ял|ел|ил|ыл|ла|ли|ло|ет|ит|ют|ут|ат|ят|ешь|ишь)$/;
/** Короче фамилии не бывают, кроме словарных («Ли», «Ким» — их знает словарь). */
const MIN_UNKNOWN_SURNAME_LEN = 3;

/** Слово — роль, должность, обращение или служебное слово (не фамилия). */
export function isRoleWord(word: string): boolean {
  const low = foldWord(word);
  return isStopWord(low) || NOT_SURNAME_WORD_RE.test(low);
}

/**
 * Может ли слово быть фамилией вплотную к «Имя Отчество».
 *
 * @param token Слово текста (того же регистра, что имя и отчество, — проверяет вызывающий).
 */
export function isSurnameNearPatronymic(token: PersonToken): boolean {
  if (token.patr || token.shape === 'initial' || token.shape === 'mixed') return false;
  if (isRoleWord(token.text)) return false;
  if (token.surn > 0) return true;
  // Слово-имя («Анна Мария Сергеевна») - не фамилия; остальное из словаря имён сюда не попадает
  if (token.name > 0) return false;
  const low = foldWord(token.text);
  return (
    low.length >= MIN_UNKNOWN_SURNAME_LEN && !VERB_LIKE_RE.test(low) && !ABSTRACT_NOUN_RE.test(low)
  );
}
